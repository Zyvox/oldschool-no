/**
 * Token compiler: tokens/*.mjs → CSS custom properties, resolved JSON and
 * contrast data. Zero dependencies.
 */
import * as palette from '../../tokens/palette.mjs';
import * as foundation from '../../tokens/foundation.mjs';
import { colorGroups, contrastPairs } from '../../tokens/semantic.mjs';
import { themes, defaultTheme, defaultVisited, statusRamps } from '../../tokens/themes.mjs';
import { accentRamp, neutralRamp, hexToRgb, contrastRatio, ACCENT_STEPS, NEUTRAL_STEPS } from '../../src/js/color.js';

export { themes, defaultTheme, contrastPairs, colorGroups };

const PREFIX = '--os-';
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const cssVar = (name) => `var(${PREFIX}${name})`;
const HEADER = '/* GENERATED by scripts/build.mjs from tokens/*.mjs — edit the sources, not this file. */\n';
const SUPPORTS_LD = '@supports (color: light-dark(#000, #fff))';
const SUPPORTS_NO_LD = '@supports not (color: light-dark(#000, #fff))';

/* ---------------------------------------------------------------------------
 * Palette
 * ------------------------------------------------------------------------ */

/** @returns {Record<string, {kind: 'accent'|'neutral', description: string, ramp: Record<string,string>}>} */
export function buildPalette() {
  const out = {};
  for (const [name, spec] of Object.entries(palette.accents)) {
    out[name] = { kind: 'accent', description: spec.description, ramp: accentRamp(spec) };
  }
  for (const [name, spec] of Object.entries(palette.neutrals)) {
    out[name] = { kind: 'neutral', description: spec.description, ramp: neutralRamp(spec) };
  }
  for (const [name, spec] of Object.entries(palette.fixed)) {
    const kind = '0' in spec.ramp ? 'neutral' : 'accent';
    out[name] = { kind, description: spec.description, ramp: spec.ramp, fixed: true };
  }
  return out;
}

/* ---------------------------------------------------------------------------
 * Primitives and roles
 * ------------------------------------------------------------------------ */

const PRIMITIVE_GROUPS = {
  font: foundation.fonts,
  text: foundation.text,
  leading: foundation.leading,
  tracking: foundation.tracking,
  weight: foundation.weight,
  space: foundation.space,
  radius: foundation.radius,
  border: foundation.border,
  duration: foundation.duration,
  ease: foundation.ease,
  z: foundation.z,
  container: foundation.container,
  icon: foundation.icon,
};

/** Flat map: 'text-md' → '1rem'. */
export function primitives() {
  const out = {};
  for (const [group, values] of Object.entries(PRIMITIVE_GROUPS)) {
    for (const [key, value] of Object.entries(values)) out[`${group}-${key}`] = value;
  }
  return out;
}

/** Replace {group.key} references with var(--os-group-key). */
function refsToVars(value) {
  return value.replace(/\{([a-z]+)\.([\w-]+)\}/g, (_, group, key) => cssVar(`${group}-${key}`));
}

/* ---------------------------------------------------------------------------
 * Color references
 * ------------------------------------------------------------------------ */

const RAMP_REF = /^(accent|neutral|visited|success|warning|danger|info)\.(\d+)$/;
const MIX_REF = /^mix\((\w+)\.(\d+)\s+(\d+)%\)$/;

/** Color reference → CSS expression. */
function colorRefToCss(ref) {
  let m = ref.match(RAMP_REF);
  if (m) return cssVar(`${m[1]}-${m[2]}`);
  m = ref.match(MIX_REF);
  if (m) return `color-mix(in srgb, ${cssVar(`${m[1]}-${m[2]}`)} ${m[3]}%, transparent)`;
  if (ref.startsWith('=')) return cssVar(`color-${ref.slice(1)}`);
  return ref;
}

function colorPairToCss({ light, dark }) {
  if (light === dark) return colorRefToCss(light);
  return `light-dark(${colorRefToCss(light)}, ${colorRefToCss(dark)})`;
}

/** Every semantic color: name → {light, dark, description, group}. */
export function semanticColors() {
  const out = {};
  for (const { group, colors } of colorGroups) {
    for (const c of colors) out[c.name] = { ...c, group };
  }
  return out;
}

/* ---------------------------------------------------------------------------
 * Theme ramp assignment
 * ------------------------------------------------------------------------ */

function themeRamps(theme) {
  return {
    accent: theme.accent,
    neutral: theme.neutral,
    visited: theme.visited ?? defaultVisited,
    ...statusRamps,
    ...(theme.status ?? {}),
  };
}

/* ---------------------------------------------------------------------------
 * CSS output
 * ------------------------------------------------------------------------ */

const block = (selector, lines, indent = '  ') =>
  `${indent}${selector} {\n${lines.map((l) => `${indent}  ${l}`).join('\n')}\n${indent}}\n`;

const decl = (name, value) => `${PREFIX}${name}: ${value};`;

export function cssPalette(pal) {
  let body = '';
  const lines = [];
  for (const [name, { description, ramp }] of Object.entries(pal)) {
    lines.push(`/* ${kebab(name)} — ${description} */`);
    for (const [step, hex] of Object.entries(ramp)) lines.push(decl(`${kebab(name)}-${step}`, hex));
  }
  body += block(':root', lines);
  return `${HEADER}/* Palette: raw ramps. Components never use these directly — themes map them onto --os-accent-* and --os-neutral-*. */\n@layer os.tokens {\n${body}}\n`;
}

export function cssFoundation() {
  const prim = primitives();
  const primLines = Object.entries(prim).map(([k, v]) => decl(k, v));
  const roleLines = foundation.roles.map(([name, value, description]) => `${decl(name, refsToVars(value))} /* ${description} */`);
  const motion = Object.keys(foundation.duration).map((k) => decl(`duration-${k}`, '0ms'));
  return `${HEADER}/* Foundation: primitive scales (declared once) and role tokens (re-declared on every theme/density scope). */
@layer os.tokens {
${block(':root', primLines)}
  /* Role tokens. Re-declared on [data-theme] and [data-density] so overrides of
     primitives and roles cascade correctly into any themed subtree. */
${block(':where(:root, [data-theme], [data-density])', roleLines)}
  @media (prefers-reduced-motion: reduce) {
${block(':root', motion, '    ')}  }
}
`;
}

export function cssSemantic() {
  const colors = semanticColors();
  const modern = Object.entries(colors).map(([name, c]) => decl(`color-${name}`, colorPairToCss(c)));
  const fallback = Object.entries(colors).map(([name, c]) => decl(`color-${name}`, colorRefToCss(c.light)));
  return `${HEADER}/* Semantic colors. Mode is decided by the inherited color-scheme:
     html (default)         → follows the OS (light dark)
     [data-mode="light"]    → light
     [data-mode="dark"]     → dark
   Browsers without light-dark() get light mode only. */
@layer os.tokens {
  :root { color-scheme: light dark; }
  [data-mode="auto"] { color-scheme: light dark; }
  [data-mode="light"] { color-scheme: light; }
  [data-mode="dark"] { color-scheme: dark; }

  ${SUPPORTS_LD} {
${block(':where(:root, [data-theme])', modern, '    ')}  }

  ${SUPPORTS_NO_LD} {
${block(':where(:root, [data-theme])', fallback, '    ')}  }
}
`;
}

export function cssThemes(pal) {
  const out = [];
  const rampLines = (role, paletteName, steps) =>
    steps.map((step) => decl(`${role}-${step}`, cssVar(`${kebab(paletteName)}-${step}`)));

  // Status + visited defaults live on :root only (identical in most themes).
  const rootLines = [];
  for (const [role, paletteName] of Object.entries(statusRamps)) {
    rootLines.push(...rampLines(role, paletteName, ACCENT_STEPS));
  }
  out.push(`  /* Status ramps (shared by all themes unless a theme overrides them). */\n${block(':root', rootLines)}`);

  for (const [name, theme] of Object.entries(themes)) {
    const selector = name === defaultTheme ? `:where(:root), [data-theme="${name}"]` : `[data-theme="${name}"]`;
    const ramps = themeRamps(theme);
    const lines = [
      `/* accent: ${ramps.accent} · neutral: ${ramps.neutral} · visited: ${ramps.visited} */`,
      ...rampLines('accent', ramps.accent, ACCENT_STEPS),
      ...rampLines('neutral', ramps.neutral, NEUTRAL_STEPS),
      ...rampLines('visited', ramps.visited, [300, 700]),
    ];
    for (const role of ['success', 'warning', 'danger', 'info']) {
      if (theme.status?.[role]) lines.push(...rampLines(role, theme.status[role], ACCENT_STEPS));
    }
    for (const [key, value] of Object.entries(theme.primitives ?? {})) lines.push(decl(key, value));
    for (const [key, value] of Object.entries(theme.roles ?? {})) lines.push(decl(key, refsToVars(value)));
    if (!pal[ramps.accent] || !pal[ramps.neutral]) throw new Error(`Theme ${name}: unknown ramp`);

    out.push(`  /* ${theme.label} — ${theme.description} */\n${block(selector, lines)}`);

    if (theme.colors) {
      const modern = Object.entries(theme.colors).map(([k, v]) => decl(`color-${k}`, colorPairToCss(v)));
      const fallback = Object.entries(theme.colors).map(([k, v]) => decl(`color-${k}`, colorRefToCss(v.light)));
      out.push(`  ${SUPPORTS_LD} {\n${block(selector, modern, '    ')}  }\n  ${SUPPORTS_NO_LD} {\n${block(selector, fallback, '    ')}  }\n`);
    }
  }
  return `${HEADER}/* Themes: which ramps feed --os-accent-*, --os-neutral-* and --os-visited-*, plus overrides.
   Apply with data-theme="…" on <html> or on any element. */
@layer os.tokens {
${out.join('\n')}}
`;
}

export function cssDensity() {
  const out = Object.entries(foundation.densities).map(([name, { description, values }]) =>
    `  /* ${name} — ${description} */\n${block(`[data-density="${name}"]`, Object.entries(values).map(([k, v]) => decl(k, v)))}`);
  return `${HEADER}/* Density modes. Apply with data-density="compact" on <html> or any element. */
@layer os.tokens {
${out.join('\n')}}
`;
}

/* ---------------------------------------------------------------------------
 * Resolution (for JSON export, docs and contrast checks)
 * ------------------------------------------------------------------------ */

function hexWithAlpha(hex, pct) {
  const [r, g, b] = hexToRgb(hex).map((c) => Math.round(c * 255));
  return `rgba(${r}, ${g}, ${b}, ${Number((pct / 100).toFixed(3))})`;
}

/**
 * Resolve every semantic color of a theme in a mode to a literal value.
 * @returns {Record<string,string>} name → '#rrggbb' | 'rgba(…)' | literal
 */
export function resolveColors(pal, themeName, mode) {
  const theme = themes[themeName];
  const ramps = themeRamps(theme);
  const base = semanticColors();
  const pick = (name) => {
    const entry = theme.colors?.[name] ?? base[name];
    if (!entry) throw new Error(`Unknown semantic color "${name}"`);
    return entry[mode];
  };
  const resolveRef = (ref, seen = new Set()) => {
    let m = ref.match(RAMP_REF);
    if (m) {
      const hex = pal[ramps[m[1]]]?.ramp[m[2]];
      if (!hex) throw new Error(`Theme ${themeName}: ${ref} does not exist`);
      return hex;
    }
    m = ref.match(MIX_REF);
    if (m) return hexWithAlpha(pal[ramps[m[1]]].ramp[m[2]], Number(m[3]));
    if (ref.startsWith('=')) {
      const target = ref.slice(1);
      if (seen.has(target)) throw new Error(`Circular alias ${target}`);
      seen.add(target);
      return resolveRef(pick(target), seen);
    }
    return ref;
  };
  const out = {};
  for (const name of Object.keys(base)) out[name] = resolveRef(pick(name));
  return out;
}

/** Resolve role tokens of a theme to literal CSS values. */
export function resolveRoles(pal, themeName, mode = 'light', density) {
  const theme = themes[themeName];
  const prim = { ...primitives(), ...(theme.primitives ?? {}) };
  const colors = resolveColors(pal, themeName, mode);
  const roles = Object.fromEntries(foundation.roles.map(([k, v]) => [k, v]));
  Object.assign(roles, theme.roles ?? {});
  if (density) Object.assign(roles, foundation.densities[density].values);
  const resolve = (value) =>
    value.replace(/\{([a-z]+)\.([\w-]+)\}/g, (_, group, key) =>
      group === 'color' ? colors[key] : resolve(prim[`${group}-${key}`] ?? `{${group}.${key}}`));
  return Object.fromEntries(Object.entries(roles).map(([k, v]) => [k, resolve(v)]));
}

/** Check all contrast pairs for a theme/mode. */
export function checkContrast(pal, themeName, mode) {
  const colors = resolveColors(pal, themeName, mode);
  return contrastPairs.map(([fg, bg, min, note]) => {
    const a = colors[fg];
    const b = colors[bg];
    const ratio = a.startsWith('#') && b.startsWith('#') ? contrastRatio(a, b) : NaN;
    return { fg, bg, min, note, fgValue: a, bgValue: b, ratio, pass: ratio >= min };
  });
}

/** Everything, resolved — becomes dist/tokens.json. */
export function tokensJson(pal, meta) {
  const prim = primitives();
  const grouped = {};
  for (const [group, values] of Object.entries(PRIMITIVE_GROUPS)) grouped[group] = { ...values };
  const out = {
    name: meta.name,
    version: meta.version,
    description: 'Oldschool design tokens, fully resolved. Generated — do not edit.',
    prefix: PREFIX,
    breakpoints: foundation.breakpoints,
    primitives: grouped,
    palette: Object.fromEntries(Object.entries(pal).map(([k, v]) => [k, v.ramp])),
    themes: {},
  };
  for (const [name, theme] of Object.entries(themes)) {
    out.themes[name] = {
      label: theme.label,
      description: theme.description,
      default: name === defaultTheme,
      ramps: themeRamps(theme),
      roles: resolveRoles(pal, name, 'light'),
      light: resolveColors(pal, name, 'light'),
      dark: resolveColors(pal, name, 'dark'),
    };
  }
  out.densities = Object.fromEntries(Object.entries(foundation.densities).map(([k, v]) => [k, v.values]));
  void prim;
  return out;
}

/** Metadata for docs pages (names, descriptions, groups). */
export function tokenMeta(pal) {
  return {
    palette: Object.fromEntries(Object.entries(pal).map(([k, v]) => [kebab(k), { kind: v.kind, description: v.description, fixed: Boolean(v.fixed), steps: Object.keys(v.ramp) }])),
    colors: colorGroups.map(({ group, colors }) => ({ group, colors: colors.map(({ name, light, dark, description }) => ({ name, light, dark, description })) })),
    roles: foundation.roles.map(([name, value, description]) => ({ name, value, description })),
    primitives: Object.fromEntries(Object.entries(PRIMITIVE_GROUPS).map(([g, v]) => [g, Object.keys(v)])),
    themes: Object.fromEntries(Object.entries(themes).map(([k, t]) => [k, { label: t.label, description: t.description, accent: t.accent, neutral: t.neutral, structural: Boolean(t.structural) }])),
    breakpoints: foundation.breakpoints,
    densities: Object.fromEntries(Object.entries(foundation.densities).map(([k, v]) => [k, v.description])),
    defaultTheme,
  };
}
