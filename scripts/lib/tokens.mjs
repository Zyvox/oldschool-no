/**
 * Token compiler: tokens/*.mjs → CSS custom properties, resolved JSON and
 * contrast data. Zero dependencies.
 */
import * as palette from '../../tokens/palette.mjs';
import * as foundation from '../../tokens/foundation.mjs';
import { colorGroups, contrastPairs } from '../../tokens/semantic.mjs';
import { themes, defaultTheme, moreContrast } from '../../tokens/themes.mjs';
import { schemeFromSeeds, seedSpec, contrastRatio } from '../../src/js/color.js';

export { themes, defaultTheme, contrastPairs, colorGroups };

const PREFIX = '--os-';
const cssVar = (name) => `var(${PREFIX}${name})`;
const HEADER = '/* GENERATED by scripts/build.mjs from tokens/*.mjs — edit the sources, not this file. */\n';

/* ---------------------------------------------------------------------------
 * Palette
 * ------------------------------------------------------------------------ */

const RAMP_INFO = {
  accent: 'The brand colour: buttons, links, focus and selected states.',
  frame: 'The frame, header bands, crumb bar, tabs and zebra rows (the accent unless palette.frame is set).',
  neutral: 'Greys for text, surfaces and rules, tinted towards the frame.',
  link: 'Links (only when palette.link is set; otherwise links use the accent ramp).',
  visited: 'Visited links.',
  success: 'Success.',
  warning: 'Warning.',
  danger: 'Danger, and the filled heart on saved items.',
  info: 'Information.',
  note: 'Post-it yellow: notices and <mark>.',
};

/** @returns {Record<string, {description: string, seed: unknown, ramp: Record<string,string>}>} */
export function buildPalette() {
  const ramps = schemeFromSeeds(palette);
  const frame = palette.frame ? (typeof palette.frame === 'string' ? palette.frame : { hue: seedSpec(palette.accent).hue, ...palette.frame }) : palette.accent;
  const seeds = { accent: palette.accent, frame, neutral: palette.neutral, link: palette.link, visited: palette.visited, ...palette.status };
  return Object.fromEntries(Object.entries(ramps).map(([name, ramp]) => [name, {
    description: RAMP_INFO[name] ?? '',
    seed: name === 'neutral' ? seeds.neutral : name === 'frame' && !palette.frame ? '= accent' : seeds[name],
    spec: name === 'neutral' ? null : seedSpec(seeds[name]),
    ramp,
  }]));
}

/* ---------------------------------------------------------------------------
 * Primitives and roles
 * ------------------------------------------------------------------------ */

const PRIMITIVE_GROUPS = {
  font: foundation.fonts,
  text: foundation.text,
  leading: foundation.leading,
  tracking: foundation.tracking,
  weight: foundation.weight,
  space: foundation.space,
  radius: foundation.radius,
  border: foundation.border,
  duration: foundation.duration,
  ease: foundation.ease,
  z: foundation.z,
  container: foundation.container,
  icon: foundation.icon,
};

/** Flat map: 'text-md' → '1rem'. */
export function primitives() {
  const out = {};
  for (const [group, values] of Object.entries(PRIMITIVE_GROUPS)) {
    for (const [key, value] of Object.entries(values)) out[`${group}-${key}`] = value;
  }
  return out;
}

/** Replace {group.key} references with var(--os-group-key). */
function refsToVars(value) {
  return value.replace(/\{([a-z]+)\.([\w-]+)\}/g, (_, group, key) => cssVar(`${group}-${key}`));
}

/* ---------------------------------------------------------------------------
 * Color references
 * ------------------------------------------------------------------------ */

const RAMP_REF = /^(accent|frame|neutral|link|visited|success|warning|danger|info|note)\.(\d+)$/;
const MIX_REF = /^mix\((\w+)\.(\d+)\s+(\d+)%\)$/;

/** Ramp name a reference points at (link falls back to accent). */
const rampName = (pal, name) => (name === 'link' && !pal.link ? 'accent' : name);

/** '#rrggbb' + percentage → '#rrggbbaa'. */
function hexAlpha(hex, pct) {
  return `${hex}${Math.round((pct / 100) * 255).toString(16).padStart(2, '0')}`;
}

/** Color reference → CSS expression. */
function colorRefToCss(pal, ref) {
  let m = ref.match(RAMP_REF);
  if (m) return cssVar(`${rampName(pal, m[1])}-${m[2]}`);
  m = ref.match(MIX_REF);
  if (m) return hexAlpha(pal[rampName(pal, m[1])].ramp[m[2]], Number(m[3]));
  if (ref.startsWith('=')) return cssVar(`color-${ref.slice(1)}`);
  return ref;
}

function colorPairToCss(pal, { light, dark }) {
  if (light === dark) return colorRefToCss(pal, light);
  return `light-dark(${colorRefToCss(pal, light)}, ${colorRefToCss(pal, dark)})`;
}

/** Every semantic color: name → {light, dark, description, group}. */
export function semanticColors() {
  const out = {};
  for (const { group, colors } of colorGroups) {
    for (const c of colors) out[c.name] = { ...c, group };
  }
  return out;
}

/** Every colour definition in play: base, each theme, more-contrast. */
function allColorDefs() {
  return [
    ...Object.values(semanticColors()),
    ...Object.values(themes).flatMap((t) => Object.values(t.colors ?? {})),
    ...Object.values(moreContrast.colors ?? {}),
  ];
}

/** Ramp steps referenced anywhere: name → Set(step). */
function usedSteps(pal) {
  const used = {};
  for (const def of allColorDefs()) {
    for (const ref of [def.light, def.dark]) {
      const m = ref.match(RAMP_REF);
      if (!m) continue;
      const name = rampName(pal, m[1]);
      (used[name] ??= new Set()).add(m[2]);
    }
  }
  return used;
}

/* ---------------------------------------------------------------------------
 * CSS output
 * ------------------------------------------------------------------------ */

const block = (selector, lines, indent = '  ') =>
  `${indent}${selector} {\n${lines.map((l) => `${indent}  ${l}`).join('\n')}\n${indent}}\n`;

const decl = (name, value) => `${PREFIX}${name}: ${value};`;

const seedLabel = (seed) => (typeof seed === 'string' ? seed : JSON.stringify(seed).replace(/"/g, ''));

/**
 * Ramps, declared once on :root. accent and neutral are emitted in full
 * (they are public API); status, link and visited ramps only with the steps
 * the semantic colours use.
 */
export function cssPalette(pal) {
  const used = usedSteps(pal);
  const lines = [];
  for (const [name, { seed, ramp }] of Object.entries(pal)) {
    const full = name === 'accent' || name === 'neutral';
    const steps = Object.keys(ramp).filter((s) => full || used[name]?.has(s));
    if (!steps.length) continue;
    lines.push(`/* ${name} — seed ${seedLabel(seed)} */`);
    for (const step of steps) lines.push(decl(`${name}-${step}`, ramp[step]));
  }
  return `${HEADER}/* Palette: ramps generated from the seeds in tokens/palette.mjs. Components never use
   these directly — they use the semantic --os-color-* tokens built on top of them. */
@layer os.tokens {
${block(':root', lines)}}
`;
}

export function cssFoundation() {
  const prim = primitives();
  const primLines = Object.entries(prim).map(([k, v]) => decl(k, v));
  const roleLines = foundation.roles.map(([name, value, description]) => `${decl(name, refsToVars(value))} /* ${description} */`);
  const motion = Object.keys(foundation.duration).map((k) => decl(`duration-${k}`, '0ms'));
  return `${HEADER}/* Foundation: primitive scales (declared once) and role tokens (re-declared on every theme scope). */
@layer os.tokens {
${block(':root', primLines)}
  /* Role tokens. Re-declared on [data-theme] so a theme's primitives (type
     sizes) re-resolve inside any themed subtree. */
${block(':where(:root, [data-theme])', roleLines)}
  @media (prefers-reduced-motion: reduce) {
${block(':root', motion, '    ')}  }
}
`;
}

export function cssSemantic(pal) {
  const colors = Object.entries(semanticColors()).map(([name, c]) => decl(`color-${name}`, colorPairToCss(pal, c)));
  return `${HEADER}/* Semantic colors. Mode is decided by the inherited color-scheme:
     html (default)         → follows the OS (light dark)
     [data-mode="light"]    → light
     [data-mode="dark"]     → dark */
@layer os.tokens {
  :root, [data-mode="auto"] { color-scheme: light dark; }
  [data-mode="light"] { color-scheme: light; }
  [data-mode="dark"] { color-scheme: dark; }

${block(':where(:root, [data-theme])', colors)}}
`;
}

function overrideLines(pal, { primitives: prim = {}, roles = {}, colors = {} }) {
  return [
    ...Object.entries(prim).map(([k, v]) => decl(k, v)),
    ...Object.entries(roles).map(([k, v]) => decl(k, refsToVars(v))),
    ...Object.entries(colors).map(([k, v]) => decl(`color-${k}`, colorPairToCss(pal, v))),
  ];
}

export function cssThemes(pal) {
  // Every key any theme overrides is declared by every theme (with the base
  // value where it has no override), so a theme scoped inside another theme's
  // subtree never inherits the outer theme's overrides.
  const base = {
    primitives: primitives(),
    roles: Object.fromEntries(foundation.roles.map(([k, v]) => [k, v])),
    colors: semanticColors(),
  };
  const keys = { primitives: new Set(), roles: new Set(), colors: new Set() };
  for (const theme of Object.values(themes)) {
    for (const kind of Object.keys(keys)) Object.keys(theme[kind] ?? {}).forEach((k) => keys[kind].add(k));
  }
  // The default theme comes first and also claims :root; later themes win on
  // <html data-theme="…"> by source order (same specificity).
  const ordered = Object.entries(themes).sort(([a], [b]) => (b === defaultTheme) - (a === defaultTheme));
  const out = [];
  for (const [name, theme] of ordered) {
    const selector = name === defaultTheme ? `:root, [data-theme="${name}"]` : `[data-theme="${name}"]`;
    const full = Object.fromEntries(Object.entries(keys).map(([kind, set]) =>
      [kind, Object.fromEntries([...set].map((k) => [k, theme[kind]?.[k] ?? base[kind][k]]))]));
    out.push(`  /* ${theme.label} — ${theme.description} */\n${block(selector, overrideLines(pal, full))}`);
  }
  out.push(`  /* Stronger values when the visitor asks for more contrast, on top of any theme. */\n  @media (prefers-contrast: more) {\n${block(':root, [data-theme]', overrideLines(pal, moreContrast), '    ')}  }\n`);
  return `${HEADER}/* Themes: overrides of primitives, roles and semantic colors on top of the base tokens.
   Apply with data-theme="…" on <html> or on any element. */
@layer os.tokens {
${out.join('\n')}}
`;
}

export function cssDensity() {
  const out = Object.entries(foundation.densities).map(([name, { description, values }]) =>
    `  /* ${name} — ${description} */\n${block(`[data-density="${name}"]`, Object.entries(values).map(([k, v]) => decl(k, refsToVars(v))))}`);
  return `${HEADER}/* Density modes. Apply with data-density="compact" on <html> or any element. */
@layer os.tokens {
${out.join('\n')}}
`;
}

/* ---------------------------------------------------------------------------
 * Resolution (for JSON export, docs and contrast checks)
 * ------------------------------------------------------------------------ */

/**
 * Resolve every semantic color of a theme in a mode to a literal value.
 * @param {{contrast?: boolean}} [opts] apply the prefers-contrast: more overrides
 * @returns {Record<string,string>} name → '#rrggbb' | '#rrggbbaa' | literal
 */
export function resolveColors(pal, themeName, mode, { contrast = false } = {}) {
  const theme = themes[themeName];
  const base = semanticColors();
  const pick = (name) => {
    const entry = (contrast && moreContrast.colors?.[name]) || theme.colors?.[name] || base[name];
    if (!entry) throw new Error(`Unknown semantic color "${name}"`);
    return entry[mode];
  };
  const resolveRef = (ref, seen = new Set()) => {
    let m = ref.match(RAMP_REF);
    if (m) {
      const hex = pal[rampName(pal, m[1])]?.ramp[m[2]];
      if (!hex) throw new Error(`Theme ${themeName}: ${ref} does not exist`);
      return hex;
    }
    m = ref.match(MIX_REF);
    if (m) return hexAlpha(pal[rampName(pal, m[1])].ramp[m[2]], Number(m[3]));
    if (ref.startsWith('=')) {
      const target = ref.slice(1);
      if (seen.has(target)) throw new Error(`Circular alias ${target}`);
      seen.add(target);
      return resolveRef(pick(target), seen);
    }
    return ref;
  };
  const out = {};
  for (const name of Object.keys(base)) out[name] = resolveRef(pick(name));
  return out;
}

/** Resolve role tokens of a theme to literal CSS values. */
export function resolveRoles(pal, themeName, mode = 'light', density) {
  const theme = themes[themeName];
  const prim = { ...primitives(), ...(theme.primitives ?? {}) };
  const colors = resolveColors(pal, themeName, mode);
  const roles = Object.fromEntries(foundation.roles.map(([k, v]) => [k, v]));
  Object.assign(roles, theme.roles ?? {});
  if (density) Object.assign(roles, foundation.densities[density].values);
  const resolve = (value) =>
    value.replace(/\{([a-z]+)\.([\w-]+)\}/g, (_, group, key) =>
      group === 'color' ? colors[key] : resolve(prim[`${group}-${key}`] ?? `{${group}.${key}}`));
  return Object.fromEntries(Object.entries(roles).map(([k, v]) => [k, resolve(v)]));
}

/** Check all contrast pairs for a theme/mode (optionally with prefers-contrast: more). */
export function checkContrast(pal, themeName, mode, opts) {
  const colors = resolveColors(pal, themeName, mode, opts);
  const hex6 = (v) => /^#[0-9a-f]{6}$/i.test(v);
  return contrastPairs.map(([fg, bg, min, note]) => {
    const a = colors[fg];
    const b = colors[bg];
    const ratio = hex6(a) && hex6(b) ? contrastRatio(a, b) : NaN;
    return { fg, bg, min, note, fgValue: a, bgValue: b, ratio, pass: ratio >= min };
  });
}

/** Everything, resolved — becomes dist/tokens.json. */
export function tokensJson(pal, meta) {
  const grouped = {};
  for (const [group, values] of Object.entries(PRIMITIVE_GROUPS)) grouped[group] = { ...values };
  const out = {
    name: meta.name,
    version: meta.version,
    description: 'Oldschool design tokens, fully resolved. Generated — do not edit.',
    prefix: PREFIX,
    breakpoints: foundation.breakpoints,
    seeds: Object.fromEntries(Object.entries(pal).map(([k, v]) => [k, v.seed])),
    palette: Object.fromEntries(Object.entries(pal).map(([k, v]) => [k, v.ramp])),
    primitives: grouped,
    themes: {},
  };
  for (const [name, theme] of Object.entries(themes)) {
    out.themes[name] = {
      label: theme.label,
      description: theme.description,
      default: name === defaultTheme,
      primitives: theme.primitives ?? {},
      roles: resolveRoles(pal, name, 'light'),
      light: resolveColors(pal, name, 'light'),
      dark: resolveColors(pal, name, 'dark'),
    };
  }
  out.densities = Object.fromEntries(Object.entries(foundation.densities).map(([k, v]) => [k, v.values]));
  return out;
}

/** Metadata for docs pages (names, descriptions, groups). */
export function tokenMeta(pal) {
  return {
    palette: Object.fromEntries(Object.entries(pal).map(([k, v]) => [k, { description: v.description, seed: v.seed, spec: v.spec, steps: Object.keys(v.ramp) }])),
    colors: colorGroups.map(({ group, colors }) => ({ group, colors: colors.map(({ name, light, dark, description }) => ({ name, light, dark, description })) })),
    roles: foundation.roles.map(([name, value, description]) => ({ name, value, description })),
    primitives: Object.fromEntries(Object.entries(PRIMITIVE_GROUPS).map(([g, v]) => [g, Object.keys(v)])),
    themes: Object.fromEntries(Object.entries(themes).map(([k, t]) => [k, { label: t.label, description: t.description }])),
    seeds: { neutral: palette.neutral, link: palette.link, frame: palette.frame ?? null },
    breakpoints: foundation.breakpoints,
    densities: Object.fromEntries(Object.entries(foundation.densities).map(([k, v]) => [k, v.description])),
    defaultTheme,
  };
}
